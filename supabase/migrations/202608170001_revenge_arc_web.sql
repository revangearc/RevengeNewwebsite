create or replace function public.consume_rate_limit(
  p_bucket_key text,
  p_kind text,
  p_limit integer,
  p_window_seconds integer
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_hits integer;
begin
  delete from public.rate_limit_buckets where expires_at <= now();
  insert into public.rate_limit_buckets (bucket_key, kind, hit_count, expires_at)
  values (p_bucket_key, p_kind, 1, now() + make_interval(secs => p_window_seconds))
  on conflict (bucket_key, kind) do update
    set hit_count = public.rate_limit_buckets.hit_count + 1
  returning hit_count into current_hits;
  return current_hits <= p_limit;
end;
$$;

revoke all on function public.consume_rate_limit(text, text, integer, integer) from public, anon, authenticated;
grant execute on function public.consume_rate_limit(text, text, integer, integer) to service_role;

create or replace function public.aggregate_analytics_day(p_day date)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  delete from public.analytics_daily where aggregate_date = p_day;
  insert into public.analytics_daily (
    aggregate_date, event_name, path, referrer_host, utm_campaign, device_class, event_count, unique_visitors
  )
  select
    p_day,
    event_name,
    path,
    referrer_host,
    utm_campaign,
    device_class,
    count(*),
    count(distinct anonymous_daily_hash)
  from public.analytics_events
  where occurred_at >= p_day::timestamptz
    and occurred_at < (p_day + 1)::timestamptz
  group by event_name, path, referrer_host, utm_campaign, device_class;
end;
$$;

create or replace function public.enforce_website_retention()
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  delete from public.analytics_events where occurred_at < now() - interval '90 days';
  delete from public.analytics_daily where aggregate_date < current_date - interval '24 months';
  delete from public.rate_limit_buckets where expires_at <= now();
end;
$$;

revoke all on function public.aggregate_analytics_day(date) from public, anon, authenticated;
revoke all on function public.enforce_website_retention() from public, anon, authenticated;
grant execute on function public.aggregate_analytics_day(date) to service_role;
grant execute on function public.enforce_website_retention() to service_role;

